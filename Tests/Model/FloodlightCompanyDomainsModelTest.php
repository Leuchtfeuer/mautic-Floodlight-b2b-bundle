    public function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub
        $this->activePlugin();
    }

    private function activePlugin(bool $isPublished = true): void
    {
        $this->client->request('GET', '/s/plugins/reload');
        $configPathTo    = self::getContainer()->get('mautic.helper.paths')->getSystemPath('root', true).'/config/blacklist.php';
        $pluginPathFrom  = self::getContainer()->get('mautic.helper.paths')->getSystemPath('plugins', true).'/'.LeuchtfeuerFloodlightB2BIntegration::INTEGRATION_NAME.'Bundle/Config/blacklist.php';
        if (!file_exists($configPathTo)) {
            copy($pluginPathFrom, $configPathTo);
        }
        $integration = $this->em->getRepository(Integration::class)->findOneBy(['name' => LeuchtfeuerFloodlightB2BIntegration::INTEGRATION_NAME]);

        if (empty($integration)) {
            $plugin      = $this->em->getRepository(Plugin::class)->findOneBy(['bundle' => 'LeuchtfeuerFloodlightB2BIntegration']);
            $integration = new Integration();
            $integration->setName('LeuchtfeuerFloodlightB2B');
            $integration->setPlugin($plugin);
        }
        $integration->setIsPublished($isPublished);
        $this->em->persist($integration);
        $this->em->flush();
        $this->useCleanupRollback = false;
        $this->setUpSymfony($this->configParams);
    }

    public function testUpdateOrCreateCompanyAndCompanyDomainAndAddOrCountLeadDomainWithHostname(): void
    {
        $floodlightCompanyDomainModel = self::getContainer()->get('mautic.leuchtfeuerfloodlightb2b.model.floodlightcompanydomains');
        $lead                         = $this->createLead();
        $dataDomainFloodlightService  = [
            'domain'  => 'le-non.de',
            'status'  => 'valid',
            'details' => [
                'hostname' => 'le-non-hostname.de',
            ],
        ];
        $companyDomain = $floodlightCompanyDomainModel->getRepository()->findOneBy(
            [
                'domain' => $dataDomainFloodlightService['domain'],
            ]
        );

        $this->assertNull($companyDomain);

        assert($floodlightCompanyDomainModel instanceof FloodlightCompanyDomainsModel);
        // Has no Company Domain and domain is valid ( not blacklisted and not failed )
        $leadDomain = $floodlightCompanyDomainModel->updateOrCreateCompanyAndCompanyDomainAndAddOrCountLeadDomain(
            $lead->getId(),
            $dataDomainFloodlightService
        );

        $companyDomain2 = $floodlightCompanyDomainModel->getRepository()->findOneBy(
            [
                'domain' => $dataDomainFloodlightService['domain'],
            ]
        );
        $this->assertNotNull($companyDomain2);
        $this->assertNotNull($leadDomain);
        $this->assertSame(1, $leadDomain->getCount());
        $this->assertSame($companyDomain2->getDomain(), $leadDomain->getDomain());
    }

    public function testUpdateOrCreateCompanyAndCompanyDomainAndAddOrCountLeadDomainWithFloodlight(): void
    {
        $floodlightCompanyDomainModel = new FloodlightCompanyDomainsModel(
            $this->em,
            self::getContainer()->get('mautic.security'),
            self::getContainer()->get('event_dispatcher'),
            $this->createMock(UrlGeneratorInterface::class),
            self::getContainer()->get('translator'),
            $this->createMock(UserHelper::class),
            $this->createMock(LoggerInterface::class),
            self::getContainer()->get('mautic.helper.core_parameters'),
            self::getContainer()->get('mautic.lead.model.company'),
            self::getContainer()->get('mautic.lead.model.lead'),
            $this->createMock(NotificationUserHelper::class),
            self::getContainer()->get('mautic.user.model.user'),
            self::getContainer()->get('mautic.leuchtfeuerfloodlightb2b.model.floodlightleaddomains'),
            self::getContainer()->get('mautic.leuchtfeuerfloodlightb2b.helper.field')
        );
        $lead = $this->createLead();

        $dataJson = json_decode(file_get_contents(__DIR__.'/../fixtures/floodlight.json'), true);
        $dataDTO  = new FloodlightDTO($dataJson);

        $dataDomainFloodlightService = [
            'domain'  => 'le-non.de',
            'status'  => 'valid',
            'details' => [
                'floodlight' => $dataDTO,
            ],
        ];

        $companyDomain = $floodlightCompanyDomainModel->getRepository()->findOneBy(
            [
                'domain' => $dataDomainFloodlightService['domain'],
            ]
        );
        $this->assertNull($companyDomain);

        // Has no Company Domain and domain is valid ( not blacklisted and not failed )
        $leadDomain = $floodlightCompanyDomainModel->updateOrCreateCompanyAndCompanyDomainAndAddOrCountLeadDomain(
            $lead->getId(),
            $dataDomainFloodlightService
        );

        $companyDomain2 = $floodlightCompanyDomainModel->getRepository()->findOneBy(
            [
                'domain' => $dataDomainFloodlightService['domain'],
            ]
        );
        $this->assertNotNull($companyDomain2);
        $this->assertNotNull($leadDomain);
        $this->assertSame(1, $leadDomain->getCount());
        $this->assertSame($companyDomain2->getDomain(), $leadDomain->getDomain());

        // Has no Company Domain and domain is valid ( not blacklisted and not failed ) add count to lead domain
        $leadDomain = $floodlightCompanyDomainModel->updateOrCreateCompanyAndCompanyDomainAndAddOrCountLeadDomain(
            $lead->getId(),
            $dataDomainFloodlightService
        );
        $this->assertNotNull($leadDomain);
        $this->assertSame(2, $leadDomain->getCount());
    }

    private function createLead(): Lead
    {
        $rand = rand(1, 1000000000);
        $lead = new Lead();
        $lead->setEmail($rand.'test1@mauit.com');
        $lead->setFirstname($rand.' first name');
        $lead->setFirstname($rand.' last name');
        $lead->setLastActive(new \DateTime());
        $lead->setIsPublished(true);
        $lead->setAddress1('address1');
        $lead->setAddress2('addres 222');
        $this->em->persist($lead);
        $this->em->flush();

        return $lead;
    }

