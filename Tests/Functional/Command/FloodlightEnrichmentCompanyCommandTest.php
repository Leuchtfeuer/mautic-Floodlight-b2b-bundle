    {
        $this->activePlugin(true, 'pro_123');
        $lead        = $this->addLead('Test Lead', 'test11@example.com');
        $leadDomain1 = $this->addLeadDomain($lead);
        $leadDomain2 = $this->addLeadDomain($lead);

