    private function addNewLeadDomain($lead, string $ipHash, int $count, $status): FloodlightLeadDomains
    {
        $floodlightLeadDomain = new FloodlightLeadDomains();
        $floodlightLeadDomain->setDateAdded(new \DateTime());
