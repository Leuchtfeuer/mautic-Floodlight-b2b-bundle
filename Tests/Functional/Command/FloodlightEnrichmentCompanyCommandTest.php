    private function addLead(string $name='Test Lead', string $email='test@example.com'): Lead
    {
        $lead = new Lead();
        $lead->setFirstName($name);
        $lead->setEmail($email);
        $lead->setDateAdded(new \DateTime());
        $lead->setDateModified(new \DateTime());
        $this->em->persist($lead);
        $this->em->flush();

