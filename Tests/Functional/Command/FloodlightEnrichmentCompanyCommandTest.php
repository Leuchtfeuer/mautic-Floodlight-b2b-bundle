<?php

namespace MauticPlugin\LeuchtfeuerFloodlightB2BBundle\Tests\Functional\Command;

use Doctrine\ORM\Exception\NotSupported;
use Doctrine\ORM\Exception\ORMException;
use Doctrine\ORM\OptimisticLockException;
use Mautic\CoreBundle\Test\MauticMysqlTestCase;
use Mautic\LeadBundle\Entity\Company;
use Mautic\PluginBundle\Entity\Integration;
use Mautic\PluginBundle\Entity\Plugin;
use MauticPlugin\LeuchtfeuerFloodlightB2BBundle\Entity\FloodlightCompanyDomains;
use MauticPlugin\LeuchtfeuerFloodlightB2BBundle\Integration\LeuchtfeuerFloodlightB2BIntegration;

class FloodlightEnrichmentCompanyCommandTest extends MauticMysqlTestCase
{
    public function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub
        $this->activePlugin();
    }

    public function testEnrichmentCompanyCommandNoCompanies(): void
    {
        $this->activePlugin();
        $commandTester = $this->testSymfonyCommand('leuchtfeuer:floodlight:enrich');
        $this->assertStringContainsString('No companies to enrich', $commandTester->getDisplay());
    }

    public function testEnrichmentCompanyCommandNoPublishedPlugin(): void
    {
        $this->activePlugin(false);
        $commandTester = $this->testSymfonyCommand('leuchtfeuer:floodlight:enrich');
        $this->assertStringContainsString('Plugin is not published', $commandTester->getDisplay());
    }

    public function testEnrichmentCompanyCommandNotConfiguredByNoApi(): void
    {
        $this->activePlugin(true, '');
        $commandTester = $this->testSymfonyCommand('leuchtfeuer:floodlight:enrich');
        $this->assertStringContainsString('Plugin is not published', $commandTester->getDisplay());
    }

    /**
     * @throws NotSupported
     */
    public function testEnrichmentCompanyCommandConfigured(): void
    {
        $this->loadCompanyAndCompanyDomain();
        $company = $this->em->getRepository(Company::class);
        $args    = [
            'filter' => [
                'force' => [
                    [
                        'column' => 'enrichment_date',
                        'expr'   => 'isNull',
                    ],
                ],
            ],
        ];
        $companies = $company->getEntities($args);
        $this->assertCount(1, $companies);
        $this->activePlugin();
        $commandTester = $this->testSymfonyCommand('leuchtfeuer:floodlight:enrich');
        $this->assertStringContainsString('Company data updated', $commandTester->getDisplay());
        $companies = $company->getEntities($args);
        $this->assertCount(0, $companies);
    }

    /**
     * @throws ORMException
     * @throws OptimisticLockException
     * @throws NotSupported
     */
    private function activePlugin($isPublished = true, $apiKey = 'pro_123'): void
    {
        $this->client->request('GET', '/s/plugins/reload');
        $integration = $this->em->getRepository(Integration::class)->findOneBy(['name' => LeuchtfeuerFloodlightB2BIntegration::INTEGRATION_NAME]);
        if (empty($integration)) {
            $plugin      = $this->em->getRepository(Plugin::class)->findOneBy(['bundle' => 'LeuchtfeuerFloodlightB2BBundle']);
            $integration = new Integration();
            $integration->setName(LeuchtfeuerFloodlightB2BIntegration::INTEGRATION_NAME);
            $integration->setPlugin($plugin);
        }
        $integration->setIsPublished($isPublished);
        $integration->setApiKeys([]);
        $this->em->persist($integration);
        $this->em->flush();
        $crawler = $this->client->request('GET', '/s/plugins/config/LeuchtfeuerFloodlightB2B');
        $form    = $crawler->selectButton('Save')->form();
        $form['integration_config[apiKeys][api_key]']->setValue($apiKey);
        $crawler = $this->client->submit($form);
        $this->assertEquals(200, $this->client->getResponse()->getStatusCode());
        $this->useCleanupRollback = false;
        $this->setUpSymfony($this->configParams);
    }

    /**
     * @throws ORMException
     * @throws OptimisticLockException
     * @throws NotSupported
     */
    private function loadCompanyAndCompanyDomain(): void
    {
        $company = new Company();
        $company->setName('Test Company');
        $company->setDateAdded(new \DateTime());
        $company->setDateModified(new \DateTime());
        $this->em->persist($company);
        $this->em->flush();
        $company = $this->em->getRepository(Company::class)->findOneBy(['name' => 'Test Company']);

        $companyDomains = new FloodlightCompanyDomains();
        $companyDomains->setCompany($company);
        $companyDomains->setDomain('test.com');
        $companyDomains->setIsPrimaryDomain(true);
        $companyDomains->setDateAdded(new \DateTime());
        $companyDomains->setDateModified(new \DateTime());
        $this->em->persist($companyDomains);
        $this->em->flush();
        $companyDomains = $this->em->getRepository(FloodlightCompanyDomains::class)->findOneBy(['domain' => 'test.com']);
    }
}
